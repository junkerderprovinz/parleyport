// Words is the sentence for why an opened page did not show, in the language r
// asks for (Accept-Language), English when the kit has none.
func Words(r *http.Request, code string) string {
	lang := sentences[language(r.Header.Get("Accept-Language"))]
	if s, ok := lang[code]; ok {
		return s
	}
	return lang["other"]
}

// language is the most wanted language of an Accept-Language header that has
// sentences, English when none has.
func language(header string) string {
	type wish struct {
		lang string
		q    float64
	}
	var wishes []wish
	for part := range strings.SplitSeq(header, ",") {
		tag, params, _ := strings.Cut(part, ";")
		w := wish{lang: strings.ToLower(strings.TrimSpace(tag)), q: 1}
		if i := strings.IndexAny(w.lang, "-_"); i >= 0 {
			w.lang = w.lang[:i]
		}
		if w.lang == "nb" || w.lang == "nn" {
			w.lang = "no"
		}
		for p := range strings.SplitSeq(params, ";") {
			if v, ok := strings.CutPrefix(strings.TrimSpace(p), "q="); ok {
				q, err := strconv.ParseFloat(v, 64)
				if err != nil {
					q = 0
				}
				w.q = q
			}
		}
		wishes = append(wishes, w)
	}
	slices.SortStableFunc(wishes, func(a, b wish) int { return cmp.Compare(b.q, a.q) })
	for _, w := range wishes {
		if _, ok := sentences[w.lang]; ok && w.q > 0 {
			return w.lang
		}
	}
	return "en"
}

